md.push('primitive.* — справочная информация о шкалах, напрямую в коде не используется.');
md.push('Темы: пути токенов идентичны, значения переключаются через [data-theme="dark"].', '');
md.push('## Семантические цвета (light / dark)', '');
md.push('| Токен | Light | Dark | Применение |');
md.push('|---|---|---|---|');
for (const l of lightLeaves.filter((x) => /^(text-and-icon|surfaces|stroke)/.test(x.path))) {
  const d = darkMap.get(l.path);
  md.push(`| ${l.path} | ${l.resolved} | ${d ? d.resolved : '—'} | ${l.token.$description || ''} |`);
}
md.push('', '## Отступы и радиусы', '');
md.push('| Токен | Значение | Применение |');
md.push('|---|---|---|');
for (const l of lightLeaves.filter((x) => ['spacing', 'borderRadius'].includes(x.token.$type))) {
  md.push(`| ${l.path} | ${cssValue({ ...l.token, $value: l.resolved })} | ${l.token.$description || ''} |`);
}
md.push('', '## Типографика (классы в tokens.css)', '');
md.push('| Класс | Состав | Применение |');
md.push('|---|---|---|');
for (const [group, tokens] of Object.entries(typeSet)) {
  for (const [name, token] of Object.entries(tokens)) {
    const r = resolve(token.$value, light);
    md.push(`| .type-${group}-${name} | ${r.fontFamily}, ${r.fontSize}/${r.lineHeight}, ${WEIGHTS[r.fontWeight] ?? r.fontWeight}, tracking ${r.letterSpacing || '0'} | ${token.$description || ''} |`);
  }
}
md.push('', '## Палитра (справочно, не использовать напрямую)', '');
md.push('| Токен | Hex | Примечание |');
md.push('|---|---|---|');
for (const l of flatten(JSON.parse(fs.readFileSync(path.join(TOKENS_DIR, 'primitive.color.json'), 'utf8')))) {
  md.push(`| ${l.path} | ${l.token.$value} | ${l.token.$description || ''} |`);
}
fs.writeFileSync(path.join(AI, 'tokens-reference.md'), md.join('\n') + '\n');

